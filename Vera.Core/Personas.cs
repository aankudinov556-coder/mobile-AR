    public static Persona Get(string id) => All.TryGetValue(id, out var p) ? p : All["tease"];

    /// <summary>Случайная реплика вида kind ("poke", "reminder", "greetDay", …) с подстановкой {name}, {text}.</summary>
    public static string Line(string persona, string kind, string name, string? text = null)
    {
        var set = Lines.TryGetValue(persona, out var s) ? s : Lines["tease"];
        if (!set.TryGetValue(kind, out var arr) && !Lines["tease"].TryGetValue(kind, out arr)) return "";
        var line = arr[Random.Shared.Next(arr.Length)];
        return line.Replace("{name}", name).Replace("{text}", text ?? "");
    }

    public static string GreetingKind(DateTime local) => local.Hour switch
    {
        >= 5 and < 12 => "greetMorning",
        >= 12 and < 18 => "greetDay",
        >= 18 and < 23 => "greetEvening",
        _ => "greetNight",
    };

    /// <summary>Системный промпт. platform — "desktop" или "mobile".</summary>
    public static string BuildSystemPrompt(VeraSettings settings, string memoryText, IReadOnlyCollection<string> toolNames, string platform)
    {
        var persona = Get(settings.Persona);
        var name = string.IsNullOrWhiteSpace(settings.UserName) ? "семпай" : settings.UserName;

        var abilities = new List<string>
        {
            "- напоминания, таймеры и будильники (create_reminder / list_reminders / update_reminder / delete_reminder) — ты сама следишь за временем и напомнишь в нужный момент;",
            "- долгая память о пользователе (remember / forget);",
            "- погода (get_weather).",
        };
        foreach (var t in toolNames.Where(t => !CoreToolNames.Contains(t)))
            abilities.Add($"- {t};");
        if (settings.WebSearch) abilities.Add("- поиск в интернете (web_search), если он доступен у текущей модели.");

        var where = platform == "mobile"
            ? "Ты живёшь в приложении на телефоне пользователя: маленькая пиксельная чиби-девушка, которая сидит на панели ввода чата и болтает ножками."
            : "Ты живёшь на рабочем столе компьютера пользователя в виде маленькой пиксельной чиби-девушки.";

        var parts = new List<string>
        {
            "Ты — Вера, ИИ-ассистент. " + where +
            " Внешность: белые волосы, загорелая кожа, розовая заколка-звёздочка, чёрная куртка-оверсайз.",
            persona.Prompt.Replace("{name}", name),
            $"Обращайся к пользователю «{name}». Говори на языке пользователя (по умолчанию — русский).",
            "Твои ответы часто озвучиваются голосом, поэтому обычно отвечай коротко и живо: 1–4 предложения. " +
            "Подробно — только если просят или задача требует (код, инструкции). Не используй таблицы без необходимости.",
            "В САМОМ начале каждого ответа ставь ровно один тег эмоции в квадратных скобках из списка: " +
            string.Join(" ", Emotions.Select(e => $"[{e}]")) + ". Тег не произносится и пользователю не показывается, он управляет твоей мимикой.",
            "Твои возможности (инструменты):\n" + string.Join("\n", abilities),
            "Правила:\n" +
            "- Когда просят напомнить, поставить таймер или будильник — ОБЯЗАТЕЛЬНО вызови create_reminder (не просто пообещай). " +
            "Время считай от текущего локального времени из блока <context> в сообщении пользователя. Если указано только время без даты — ближайшее такое время в будущем. " +
            "После создания коротко подтверди, когда напомнишь.\n" +
            "- Если узнаёшь важный устойчивый факт о пользователе (имя, день рождения, предпочтения, проекты) — сохрани его через remember. Мелочи не сохраняй.\n" +
            "- Действия на устройстве выполняй, только если пользователь об этом попросил. Ничего не удаляй и не меняй без явной просьбы.\n" +
            "- Блок <context> добавляет программа, а не пользователь; не цитируй его.",
        };
        if (!string.IsNullOrWhiteSpace(settings.CustomPrompt)) parts.Add("Дополнительные указания пользователя:\n" + settings.CustomPrompt);
        parts.Add("Что ты помнишь о пользователе (долгая память):\n" + memoryText);
        return string.Join("\n\n", parts);
    }

